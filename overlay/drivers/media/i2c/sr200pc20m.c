static int sprd_cam_init_controls(struct sprd_cam *cam)
{
	struct v4l2_fwnode_device_properties props;
	struct v4l2_ctrl_handler *hdl = &cam->ctrls;
	int ret;

	v4l2_ctrl_handler_init(hdl, 10);
	cam->link_freq = v4l2_ctrl_new_int_menu(hdl, &sprd_cam_ctrl_ops,
						V4L2_CID_LINK_FREQ,
						ARRAY_SIZE(link_freqs) - 1, 0,
						link_freqs);
	cam->pixel_rate = v4l2_ctrl_new_std(hdl, &sprd_cam_ctrl_ops,
					    V4L2_CID_PIXEL_RATE,
					    1, 100000000, 1, 18000000);
	v4l2_ctrl_new_std(hdl, &sprd_cam_ctrl_ops,
			  V4L2_CID_EXPOSURE, 1, 1000, 1, 100);
	v4l2_ctrl_new_std(hdl, &sprd_cam_ctrl_ops,
			  V4L2_CID_ANALOGUE_GAIN, 1, 100, 1, 10);
	v4l2_ctrl_new_std(hdl, &sprd_cam_ctrl_ops,
			  V4L2_CID_GAIN, 1, 100, 1, 10);
	v4l2_ctrl_new_std_menu(hdl, &sprd_cam_ctrl_ops,
			       V4L2_CID_EXPOSURE_AUTO,
			       V4L2_EXPOSURE_MANUAL, 0, V4L2_EXPOSURE_AUTO);
	v4l2_ctrl_new_std(hdl, &sprd_cam_ctrl_ops,
			  V4L2_CID_AUTOGAIN, 0, 1, 1, 1);
	if (cam->link_freq)
		cam->link_freq->flags |= V4L2_CTRL_FLAG_READ_ONLY;
	if (cam->pixel_rate)
		cam->pixel_rate->flags |= V4L2_CTRL_FLAG_READ_ONLY;

	ret = v4l2_fwnode_device_parse(cam->dev, &props);
	if (!ret)
		v4l2_ctrl_new_fwnode_properties(hdl, &sprd_cam_ctrl_ops, &props);
	if (hdl->error) {
		ret = hdl->error;
		v4l2_ctrl_handler_free(hdl);
		return ret;
	}
	cam->sd.ctrl_handler = hdl;
	return 0;
}

static int sprd_cam_check_endpoint(struct sprd_cam *cam)
{
	struct v4l2_fwnode_endpoint ep = { .bus_type = V4L2_MBUS_CSI2_DPHY };
	struct fwnode_handle *fw;
	int ret;

	fw = fwnode_graph_get_next_endpoint(dev_fwnode(cam->dev), NULL);
	if (!fw)
		return dev_err_probe(cam->dev, -EINVAL, "no endpoint\n");
	ret = v4l2_fwnode_endpoint_alloc_parse(fw, &ep);
	fwnode_handle_put(fw);
	if (ret)
		return dev_err_probe(cam->dev, ret, "bad endpoint\n");
	if (ep.bus.mipi_csi2.num_data_lanes != NUM_LANES)
		ret = dev_err_probe(cam->dev, -EINVAL, "one data lane only\n");
	v4l2_fwnode_endpoint_free(&ep);
	return ret;
}

static int sprd_cam_detect(struct sprd_cam *cam)
{
	struct i2c_client *client = to_i2c_client(cam->dev);
	const u16 addrs[] = { client->addr, 0x21, 0x20, 0x30 };
	u64 id = 0;
	int a, tries, ret = -ENODEV;
	int pwdn_pol;

	for (pwdn_pol = 0; pwdn_pol < 2; pwdn_pol++) {
		if (pwdn_pol == 1) {
			/* Invert PWDN in case polarity is opposite */
			dev_info(cam->dev, "Retrying probe with inverted PWDN pin...\n");
			gpiod_set_value_cansleep(cam->powerdown_gpio, 1);
			msleep(20);
		}

		for (a = 0; a < ARRAY_SIZE(addrs); a++) {
			client->addr = addrs[a];
			for (tries = 0; tries < 3; tries++) {
				/* 1. Try SiliconFile SR030PC50 / SR200PC20M (reg 0x03=0x00, reg 0x04 -> 0xb8 / 0xb4) */
				cci_write(cam->regmap, CCI_REG8(0x03), 0x00, NULL);
				ret = cci_read(cam->regmap, CCI_REG8(0x04), &id, NULL);
				if (!ret && id == 0xb8) {
					cam->type = SENSOR_SR030PC50;
					cam->pwdn_invert = (pwdn_pol == 1);
					dev_info(cam->dev, "Found SiliconFile SR030PC50 at 0x%02x (chip id 0x%llx)\n",
						 client->addr, id);
					return 0;
				}
				if (!ret && id == 0xb4) {
					cam->type = SENSOR_SR200PC20M;
					cam->pwdn_invert = (pwdn_pol == 1);
					dev_info(cam->dev, "Found SiliconFile SR200PC20M at 0x%02x (chip id 0x%llx)\n",
						 client->addr, id);
					return 0;
				}

				/* 2. Try GalaxyCore GC0310 (reg 0xfe=0x00, reg 0xf0 -> 0xa3) */
				cci_write(cam->regmap, CCI_REG8(0xfe), 0x00, NULL);
				ret = cci_read(cam->regmap, CCI_REG8(0xf0), &id, NULL);
				if (!ret && (id == 0xa3 || id == 0xa310)) {
					cam->type = SENSOR_GC0310;
					cam->pwdn_invert = (pwdn_pol == 1);
					dev_info(cam->dev, "Found GalaxyCore GC0310 at 0x%02x (chip id 0x%llx)\n",
						 client->addr, id);
					return 0;
				}
				msleep(10);
			}
		}
	}

	dev_err(cam->dev, "Sensor ID probe failed on all addresses (last id 0x%llx, ret %d)\n", id, ret);
	return -ENODEV;
}

static int sprd_cam_probe(struct i2c_client *client)
{
	struct device *dev = &client->dev;
	struct sprd_cam *cam;
	int i, ret;

	cam = devm_kzalloc(dev, sizeof(*cam), GFP_KERNEL);
	if (!cam)
		return -ENOMEM;
	cam->dev = dev;
	cam->width = 640;
	cam->height = 480;

	v4l2_i2c_subdev_init(&cam->sd, client, &sprd_cam_subdev_ops);
	cam->sd.internal_ops = &sprd_cam_internal_ops;

	ret = sprd_cam_check_endpoint(cam);
	if (ret)
		return ret;

	cam->regmap = devm_cci_regmap_init_i2c(client, 8);
	if (IS_ERR(cam->regmap))
		return PTR_ERR(cam->regmap);

	cam->mclk = devm_clk_get(dev, NULL);
	if (IS_ERR(cam->mclk))
		return dev_err_probe(dev, PTR_ERR(cam->mclk), "no mclk\n");
	ret = clk_set_rate(cam->mclk, MCLK_HZ);
	if (ret)
		return dev_err_probe(dev, ret, "mclk rate\n");

	cam->reset_gpio = devm_gpiod_get(dev, "reset", GPIOD_OUT_HIGH);
	if (IS_ERR(cam->reset_gpio))
		return dev_err_probe(dev, PTR_ERR(cam->reset_gpio), "reset\n");
	cam->powerdown_gpio = devm_gpiod_get(dev, "powerdown", GPIOD_OUT_HIGH);
	if (IS_ERR(cam->powerdown_gpio))
		return dev_err_probe(dev, PTR_ERR(cam->powerdown_gpio), "powerdown\n");

	for (i = 0; i < ARRAY_SIZE(sensor_supplies); i++)
		cam->supplies[i].supply = sensor_supplies[i];
	ret = devm_regulator_bulk_get(dev, ARRAY_SIZE(cam->supplies), cam->supplies);
	if (ret)
		return dev_err_probe(dev, ret, "supplies\n");

	ret = sprd_cam_power_on(dev);
	if (ret)
		return dev_err_probe(dev, ret, "power on\n");

	ret = sprd_cam_detect(cam);
	if (ret)
		goto err_power;

	ret = sprd_cam_init_controls(cam);
	if (ret)
		goto err_power;

	cam->sd.flags |= V4L2_SUBDEV_FL_HAS_DEVNODE;
	cam->sd.entity.function = MEDIA_ENT_F_CAM_SENSOR;
	cam->pad.flags = MEDIA_PAD_FL_SOURCE;
	ret = media_entity_pads_init(&cam->sd.entity, 1, &cam->pad);
	if (ret)
		goto err_ctrls;

	cam->sd.state_lock = cam->ctrls.lock;
	ret = v4l2_subdev_init_finalize(&cam->sd);
	if (ret)
		goto err_pads;

	pm_runtime_set_active(dev);
	pm_runtime_get_noresume(dev);
	pm_runtime_enable(dev);
	pm_runtime_set_autosuspend_delay(dev, 1000);
	pm_runtime_use_autosuspend(dev);

	ret = v4l2_async_register_subdev_sensor(&cam->sd);
	if (ret)
		goto err_pm;

	pm_runtime_put_autosuspend(dev);
	dev_info(dev, "Camera sensor registered successfully!\n");
	return 0;

err_pm:
	pm_runtime_disable(dev);
	pm_runtime_set_suspended(dev);
	pm_runtime_put_noidle(dev);
	v4l2_subdev_cleanup(&cam->sd);
err_pads:
	media_entity_cleanup(&cam->sd.entity);
err_ctrls:
	v4l2_ctrl_handler_free(&cam->ctrls);
err_power:
	sprd_cam_power_off(dev);
	return ret;
}

static void sprd_cam_remove(struct i2c_client *client)
{
	struct v4l2_subdev *sd = i2c_get_clientdata(client);
	struct sprd_cam *cam = to_sprd_cam(sd);

	pm_runtime_disable(cam->dev);
	if (!pm_runtime_status_suspended(cam->dev))
		sprd_cam_power_off(cam->dev);
	pm_runtime_set_suspended(cam->dev);

	v4l2_async_unregister_subdev(sd);
	v4l2_subdev_cleanup(sd);
	media_entity_cleanup(&cam->sd.entity);
	v4l2_ctrl_handler_free(&cam->ctrls);
}

